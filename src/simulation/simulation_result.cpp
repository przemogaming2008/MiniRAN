#include "miniran/simulation/simulation_result.h"

#include <iomanip>
#include <sstream>

namespace miniran {

std::string SimulationResult::summary() const {
    std::ostringstream output;

    output << "Scenario: " << scenarioName << '\n';
    output << "Duration [ms]: " << totalDurationMs << '\n';
    output << "UE count: " << ueCount << '\n';
    output << "Cleanly detached sessions: " << cleanlyDetachedSessions << '\n';
    output << "Active sessions at end: " << activeSessionsAtEnd << '\n';
    output << "Expired sessions: " << expiredSessions << '\n';

    output << '\n';
    output << "Global network metrics:" << '\n';
    output << "  Packets dropped in network: " << packetsDroppedInNetwork << '\n';
    output << "  Packets dropped by loss: " << packetsDroppedByLoss << '\n';
    output << "  Packets dropped by queue: " << packetsDroppedByQueue << '\n';
    output << "  Packets delivered by network: " << packetsDeliveredByNetwork << '\n';

    output << '\n';
    output << "Global core metrics:" << '\n';
    output << "  Uplink packets accepted by core: " << uplinkPacketsAcceptedByCore << '\n';
    output << "  Uplink bytes accepted by core: " << uplinkBytesAcceptedByCore << '\n';
    output << "  Downlink packets delivered to UE: " << downlinkPacketsDeliveredToUe << '\n';
    output << "  Downlink bytes delivered to UE: " << downlinkBytesDeliveredToUe << '\n';

    output << std::fixed << std::setprecision(3);
    output << "  Total uplink throughput [Mbps]: " << totalUplinkThroughputMbps << '\n';
    output << "  Total downlink throughput [Mbps]: " << totalDownlinkThroughputMbps << '\n';

    if (!ueResults.empty()) {
        output << '\n';
        output << "UE results:" << '\n';

        for (const auto& ueResult : ueResults) {
            output << "UE " << ueResult.ueId << " / node " << ueResult.nodeId << ":" << '\n';

            output << "  Session id: " << ueResult.sessionId << '\n';
            output << "  Attach succeeded: " << (ueResult.attachSucceeded ? "yes" : "no") << '\n';
            output << "  Traffic started: " << (ueResult.trafficStarted ? "yes" : "no") << '\n';
            output << "  Detach succeeded: " << (ueResult.detachSucceeded ? "yes" : "no") << '\n';
            output << "  Active at end: " << (ueResult.activeAtEnd ? "yes" : "no") << '\n';
            output << "  Final UE state: " << toString(ueResult.finalUeState) << '\n';
            output << "  End reason: " << toString(ueResult.endReason) << '\n';

            output << "  Attach retries: " << ueResult.attachRetries << '\n';
            output << "  Detach retries: " << ueResult.detachRetries << '\n';
            output << "  Heartbeats sent: " << ueResult.heartbeatsSent << '\n';
            output << "  Heartbeat ACKs received: " << ueResult.heartbeatAcksReceived << '\n';

            output << "  Uplink generated packets: " << ueResult.uplinkPacketsGenerated << '\n';
            output << "  Uplink generated bytes: " << ueResult.uplinkBytesGenerated << '\n';
            output << "  Uplink sent packets: " << ueResult.uplinkPacketsSent << '\n';
            output << "  Uplink sent bytes: " << ueResult.uplinkBytesSent << '\n';
            output << "  Uplink packets delivered by network: " << ueResult.uplinkPacketsDeliveredByNetwork << '\n';
            output << "  Uplink bytes delivered by network: " << ueResult.uplinkBytesDeliveredByNetwork << '\n';
            output << "  Uplink packets accepted by core: " << ueResult.uplinkPacketsAcceptedByCore << '\n';
            output << "  Uplink bytes accepted by core: " << ueResult.uplinkBytesAcceptedByCore << '\n';
            output << "  Uplink throughput [Mbps]: " << ueResult.uplinkThroughputMbps << '\n';

            output << "  Downlink generated packets: " << ueResult.downlinkPacketsGenerated << '\n';
            output << "  Downlink generated bytes: " << ueResult.downlinkBytesGenerated << '\n';
            output << "  Downlink sent packets: " << ueResult.downlinkPacketsSent << '\n';
            output << "  Downlink sent bytes: " << ueResult.downlinkBytesSent << '\n';
            output << "  Downlink packets received by UE: " << ueResult.downlinkPacketsReceivedByUe << '\n';
            output << "  Downlink bytes received by UE: " << ueResult.downlinkBytesReceivedByUe << '\n';
            output << "  Downlink throughput [Mbps]: " << ueResult.downlinkThroughputMbps << '\n';

            if (!ueResult.notes.empty()) {
                output << "  Notes:" << '\n';
                for (const auto& note : ueResult.notes) {
                    output << "    - " << note << '\n';
                }
            }
        }
    }

    if (!notes.empty()) {
        output << '\n';
        output << "Global notes:" << '\n';
        for (const auto& note : notes) {
            output << "  - " << note << '\n';
        }
    }

    return output.str();
}

}  // namespace miniran
